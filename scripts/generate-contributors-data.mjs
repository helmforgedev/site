import { mkdir, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';

const [repo = 'helmforgedev/charts', outputPath = 'src/data/contributors.ts'] = process.argv.slice(2);
const token = process.env.GITHUB_TOKEN;

const headers = {
  Accept: 'application/vnd.github+json',
  'User-Agent': 'helmforge-contributors-data',
};

if (token) {
  headers.Authorization = `Bearer ${token}`;
}

function sleep(ms) {
  return new Promise((resolve) => {
    setTimeout(resolve, ms);
  });
}

async function fetchJsonWithRetry(url, label) {
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    let response;

    try {
      const controller = new AbortController();
      const timeoutId = setTimeout(() => {
        controller.abort();
      }, 15000);

      try {
        response = await fetch(url, { headers, signal: controller.signal });
      } finally {
        clearTimeout(timeoutId);
      }
    } catch (error) {
      if (attempt === 3) {
        const message = error instanceof Error ? error.message : String(error);
        throw new Error(`Failed to fetch ${label}: ${message}`, {
          cause: error,
        });
      }

      await sleep(attempt * 1000);
      continue;
    }

    if (response.ok) {
      return response.json();
    }

    const retryable = [403, 429, 500, 502, 503, 504].includes(response.status);

    if (!retryable || attempt === 3) {
      throw new Error(`Failed to fetch ${label}: ${response.status} ${response.statusText}`);
    }

    const retryAfter = Number.parseInt(response.headers.get('retry-after') ?? '', 10);
    await sleep(Number.isFinite(retryAfter) ? retryAfter * 1000 : attempt * 1000);
  }

  throw new Error(`Failed to fetch ${label}`);
}

async function mapWithConcurrency(items, limit, mapper) {
  const results = [];

  for (let index = 0; index < items.length; index += limit) {
    const batch = items.slice(index, index + limit);
    results.push(...(await Promise.all(batch.map(mapper))));
  }

  return results;
}

async function fetchContributors(repoName) {
  const contributors = [];

  for (let page = 1; page <= 10; page += 1) {
    const url = `https://api.github.com/repos/${repoName}/contributors?per_page=100&page=${page}`;
    const pageContributors = await fetchJsonWithRetry(url, `contributors for ${repoName}`);
    contributors.push(...pageContributors);

    if (pageContributors.length < 100) {
      break;
    }
  }

  return contributors;
}

async function fetchUser(login) {
  return fetchJsonWithRetry(`https://api.github.com/users/${login}`, `user ${login}`);
}

function isAutomationAccount(contributor) {
  const login = contributor.login.toLowerCase();
  return contributor.type === 'Bot' || login.endsWith('[bot]') || /(^|[-_])bot($|[-_])/.test(login);
}

function quote(value) {
  return `'${String(value).replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

const contributors = await mapWithConcurrency(
  (await fetchContributors(repo)).filter((contributor) => !isAutomationAccount(contributor)),
  4,
  async (contributor) => {
    const user = await fetchUser(contributor.login);

    return {
      ...contributor,
      displayName: user.name || contributor.login,
    };
  },
);

function sizedAvatarUrl(value, size) {
  const avatarUrl = new URL(value);
  avatarUrl.searchParams.set('s', String(size));
  return avatarUrl.toString();
}

const rows = contributors
  .map(
    (contributor) => `  {
    name: ${quote(contributor.displayName)},
    login: ${quote(contributor.login)},
    profileUrl: ${quote(contributor.html_url)},
    avatarUrl: ${quote(sizedAvatarUrl(contributor.avatar_url, 96))},
    contributions: ${contributor.contributions},
  },`,
  )
  .join('\n');

const contents = `export type Contributor = {
  name: string;
  login: string;
  profileUrl: string;
  avatarUrl: string;
  contributions: number;
};

// Generated by scripts/generate-contributors-data.mjs from ${repo}.
export const chartContributors: Contributor[] = [
${rows}
];
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, contents);
